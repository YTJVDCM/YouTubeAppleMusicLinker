import type { PublicMetadata } from '../shared/contracts';
import { appleMusicUrl } from '../shared/urls';
import { normalize, parseTitle } from '../matching/normalize';
import { similarity } from '../matching/score';
type Credit = NonNullable<PublicMetadata['credits']>[number];
const clean = (value: string | null | undefined, max = 500) => value?.replace(/\s+/g, ' ').trim().slice(0, max) ?? '';
const labels: Record<string, 'title' | 'artist' | 'album'> = {
  song: 'title', title: 'title', 'song title': 'title', '曲': 'title', '曲名': 'title', '楽曲': 'title',
  artist: 'artist', artists: 'artist', 'アーティスト': 'artist',
  album: 'album', 'アルバム': 'album', '収録アルバム': 'album',
};
const labelKey = (value: string) => labels[value.normalize('NFKC').replace(/[:：]\s*$/, '').trim().toLowerCase()];

/** Read public, current-watch DOM only. Never access player internals or private APIs. */
export function extractMetadata(document: Document, videoId: string): PublicMetadata | undefined {
  const watch = [...document.querySelectorAll('ytd-watch-flexy')];
  const active = watch.find(el => el.getAttribute('video-id') === videoId);
  if (watch.some(el => el.hasAttribute('video-id')) && !active) return;
  const scope = active ?? document;
  const title = clean(scope.querySelector('h1.ytd-watch-metadata, h1 yt-formatted-string')?.textContent) ||
    clean(document.title.replace(/ - YouTube$/, ''));
  const channel = clean(scope.querySelector('#owner #channel-name a')?.textContent, 300);
  const duration = scope.querySelector('video')?.duration;
  const description = scope.querySelector<HTMLElement>('#description-inline-expander, #description');
  const credits: Credit[] = [];
  const albumHints: string[] = [];
  for (const section of scope.querySelectorAll('ytd-video-description-music-section-renderer, ytd-metadata-row-container-renderer')) {
    if (section.querySelector('ytd-metadata-row-container-renderer')) continue;
    let current: Partial<Credit> = {};
    const flush = () => { if (current.title && current.artist) credits.push(current as Credit); current = {}; };
    for (const row of section.querySelectorAll('ytd-metadata-row-renderer, ytd-info-row-renderer')) {
      const key = labelKey(clean(row.querySelector('#title, .metadata-row-title')?.textContent));
      const value = clean(row.querySelector('#contents, #default-metadata, .metadata-row-contents')?.textContent, key === 'artist' ? 300 : 500);
      if (!key || !value) continue;
      if (key === 'title' && current.title) flush();
      current[key] = value;
      if (key === 'album') albumHints.push(value);
    }
    flush();
  }
  // Some YouTube layouts expose album/artist credits as rich metadata cards.
  for (const card of description?.querySelectorAll('ytd-rich-metadata-renderer') ?? []) {
    const key = labelKey(clean(card.querySelector('#subtitle')?.textContent));
    if (key === 'album') { const value = clean(card.querySelector('#title')?.textContent); if (value) albumHints.push(value); }
  }
  if (!credits.length && description) {
    const generated = parseGeneratedDescription(description.innerText || '', title, channel) ??
      parseGeneratedDescription(description.textContent || '', title, channel);
    if (generated) credits.push(generated);
  }
  const distinct = [...new Map(credits.map(c => [`${c.title}\0${c.artist}\0${c.album ?? ''}`, c])).values()].slice(0, 10);
  const uniqueAlbums = [...new Set(albumHints)];
  const album = distinct.length === 1 ? distinct[0].album ?? (uniqueAlbums.length === 1 ? uniqueAlbums[0] : undefined) :
    distinct.length === 0 && uniqueAlbums.length === 1 ? uniqueAlbums[0] : undefined;
  const links = [...(description?.querySelectorAll<HTMLAnchorElement>('a[href]') ?? [])]
    .map(a => a.href).filter(u => !!appleMusicUrl(u)).slice(0, 5);
  return { title, channel, album, credits: distinct.length ? distinct : undefined,
    durationSeconds: duration && Number.isFinite(duration) && duration > 0 && duration < 86400 ? duration : undefined,
    directAppleMusicUrls: links };
}

export function parseGeneratedDescription(text: string, videoTitle: string, channel: string): Credit | undefined {
  const lines = text.slice(0, 12000).split(/\r?\n/).map(line => clean(line)).filter(Boolean);
  const start = lines.findIndex(line => /^Provided to YouTube by\s/i.test(line));
  if (start < 0 || !lines.some(line => /^Auto-generated by YouTube\.?$/i.test(line))) return;
  const song = lines[start + 1], album = lines[start + 2];
  if (!song || !album || /^(?:℗|©|Released on:|Composer:|Provided to)/i.test(album)) return;
  const pieces = song.split(/\s+[·•]\s+/);
  if (pieces.length !== 2 || pieces[0].length > 500 || pieces[1].length > 300) return;
  const parsed = parseTitle(videoTitle, channel);
  // A pasted description for a different song must not replace the actual title.
  if (similarity(normalize(parsed.title), pieces[0]) < .8) return;
  return { title: pieces[0], artist: pieces[1], album };
}
