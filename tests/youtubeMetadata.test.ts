// @vitest-environment happy-dom
import { it, expect, afterEach } from 'vitest';
import { extractMetadata, parseGeneratedDescription } from '../src/youtube/metadata';
import { metadataValid } from '../src/shared/validation';
afterEach(() => document.body.replaceChildren());
it('reads Japanese music credits including album and ignores unrelated page content', () => {
  document.body.innerHTML = `<ytd-watch-flexy video-id="abcdefghijk">
    <h1 class="ytd-watch-metadata">Artist - Song (Official Audio)</h1>
    <div id="owner"><div id="channel-name"><a>Uploader</a></div></div>
    <div id="description"><ytd-metadata-row-container-renderer>
      <ytd-metadata-row-renderer><span id="title">曲</span><span id="contents">Song</span></ytd-metadata-row-renderer>
      <ytd-metadata-row-renderer><span id="title">アーティスト</span><span id="contents">Artist</span></ytd-metadata-row-renderer>
      <ytd-metadata-row-renderer><span id="title">アルバム</span><span id="contents">Original Album</span></ytd-metadata-row-renderer>
    </ytd-metadata-row-container-renderer><a href="https://music.apple.com/jp/album/2?i=1">配信</a></div>
    </ytd-watch-flexy><div id="related"><span>Wrong Album</span></div>`;
  const metadata = extractMetadata(document, 'abcdefghijk');
  expect(metadata).toMatchObject({ channel: 'Uploader', album: 'Original Album',
    credits: [{ title: 'Song', artist: 'Artist', album: 'Original Album' }], directAppleMusicUrls: ['https://music.apple.com/jp/album/2?i=1'] });
  expect(metadataValid(metadata)).toBe(true);
});
it('keeps multiple songs and their albums separate rather than inventing a single album', () => {
  document.body.innerHTML = `<h1 class="ytd-watch-metadata">Artist - Song</h1><div id="description">
    <ytd-video-description-music-section-renderer>${['One', 'Two'].map(title => `<ytd-metadata-row-container-renderer>
      <ytd-info-row-renderer><span id="title">Song</span><span id="default-metadata">${title}</span></ytd-info-row-renderer>
      <ytd-info-row-renderer><span id="title">Artist</span><span id="default-metadata">Artist</span></ytd-info-row-renderer>
      <ytd-info-row-renderer><span id="title">Album</span><span id="default-metadata">Album ${title}</span></ytd-info-row-renderer>
    </ytd-metadata-row-container-renderer>`).join('')}</ytd-video-description-music-section-renderer></div>`;
  const result = extractMetadata(document, 'abcdefghijk');
  expect(result?.credits).toHaveLength(2); expect(result?.album).toBeUndefined();
  expect(result?.credits?.[1].album).toBe('Album Two');
});
it('parses a matching auto-generated description but refuses unrelated or unstructured descriptions', () => {
  const description = 'Provided to YouTube by Label\nSong · Artist\nOriginal Album\n℗ 2025 Label\nReleased on: 2025-01-01\nAuto-generated by YouTube.';
  expect(parseGeneratedDescription(description, 'Song', 'Artist - Topic')).toEqual({ title: 'Song', artist: 'Artist', album: 'Original Album' });
  expect(parseGeneratedDescription(description, 'Completely Different', '')).toBeUndefined();
  expect(parseGeneratedDescription('Song · Artist\nOriginal Album', 'Song', '')).toBeUndefined();
  document.body.innerHTML = '<h1 class="ytd-watch-metadata">Song</h1><div id="description"></div>';
  document.querySelector('#description')!.textContent = description;
  expect(extractMetadata(document, 'abcdefghijk')?.album).toBe('Original Album');
});
it('waits for current-watch DOM after SPA navigation and reads album cards without private APIs', () => {
  document.body.innerHTML = `<ytd-watch-flexy video-id="abcdefghijk"><h1 class="ytd-watch-metadata">Song</h1>
    <div id="description"><ytd-rich-metadata-renderer><span id="title">Album</span><span id="subtitle">アルバム</span></ytd-rich-metadata-renderer></div>
    </ytd-watch-flexy>`;
  expect(extractMetadata(document, 'lmnopqrstuv')).toBeUndefined();
  document.querySelector('ytd-watch-flexy')!.setAttribute('video-id', 'lmnopqrstuv');
  expect(extractMetadata(document, 'lmnopqrstuv')?.album).toBe('Album');
});
it('bounds album fields at the message boundary', () => {
  expect(metadataValid({ title: 'Song', channel: '', album: 'x'.repeat(501) })).toBe(false);
  expect(metadataValid({ title: 'Song', channel: '', credits: [{ title: 'Song', artist: 'Artist', album: {} }] })).toBe(false);
});
